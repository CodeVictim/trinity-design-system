// Builds tokens/1-primitives/*.css + primitives.json from tokens/source/figma-primitives.json
// Source = read-only pull from Figma (Brand Colors + Primitives collections, text + effect styles).
// Re-run after re-pulling from Figma:  node scripts/build-primitives.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const src = JSON.parse(readFileSync(ROOT + 'tokens/source/figma-primitives.json', 'utf8'));
// which Style/Layout tokens alias each primitive (read-only pull) → "used by" on doc pages
let usage = {};
try { usage = JSON.parse(readFileSync(ROOT + 'tokens/source/figma-usage.json', 'utf8')); } catch { /* optional */ }
const OUT = ROOT + 'tokens/1-primitives/';

const cssName = (name) => '--' + name.trim().toLowerCase().replace(/[\/\s]+/g, '-');
const lastNum = (name) => { const m = name.match(/(\d+(?:\.\d+)?)\s*$/); return m ? parseFloat(m[1]) : Infinity; };
const round = (n) => Math.round(n * 1000) / 1000;
const header = (title, note) => `/* ============================================================================
   TRINITY DESIGN SYSTEM — PRIMITIVES: ${title}
   Tier: 1 · Primitives (raw values, single mode)
   Source: Figma "${src._meta.file}" (${src._meta.fileKey}), pulled ${src._meta.pulled}
   GENERATED by scripts/build-primitives.mjs — do not edit by hand.${note ? '\n   ' + note : ''}
   ============================================================================ */\n\n:root {\n`;

const tokens = []; // normalized list for stories
const addTok = (t) => { tokens.push(t); return t; };

// ---------- classify ----------
const brand = src['Brand Colors'];
const prims = src['Primitives'];
const colorGroup = (n) => n.split('/')[0];

function colorFile(list, title, note, grouper) {
  const groups = {};
  for (const v of list) (groups[grouper(v.name)] ??= []).push(v);
  let css = header(title, note);
  for (const [g, items] of Object.entries(groups)) {
    css += `\n  /* ---- ${g} ---- */\n`;
    items.sort((a, b) => lastNum(a.name) - lastNum(b.name) || a.name.localeCompare(b.name));
    for (const v of items) {
      const value = v.value;
      const isAlias = !!v.alias;
      const ref = isAlias && brand.some(b => b.name === v.alias) ? `var(${cssName(v.alias)})` : value;
      const flag = isAlias ? `  /* ⚠ alias → ${v.alias}${v.aliasNote ? ' · ' + v.aliasNote : ''} — not a raw primitive */` : '';
      css += `  ${cssName(v.name)}: ${ref};${flag}\n`;
      addTok({ category: 'color', file: title, group: g, figma: v.name, css: cssName(v.name), value, alias: v.alias || null, note: v.aliasNote || null });
    }
  }
  return css + '}\n';
}

// Brand colors (non-data) vs data colors
const brandCore = brand.filter(v => !v.name.startsWith('data/'));
const dataColors = brand.filter(v => v.name.startsWith('data/'));
writeFileSync(OUT + 'primitives-color.css', colorFile(brandCore, 'COLOR', 'Figma collection: Brand Colors (excluding data/*)', colorGroup));
writeFileSync(OUT + 'primitives-data-color.css', colorFile(dataColors, 'DATA COLOR', 'Figma collection: Brand Colors → data/*', n => n.split('/').slice(0, 2).join('/')));

// Number primitives
function numberFile(prefixes, title, unitFn, groupFn = n => n.split('/').slice(0, -1).join('/') || n) {
  const items = prims.filter(v => prefixes.some(p => v.name.startsWith(p + '/')));
  const groups = {};
  for (const v of items) (groups[groupFn(v.name)] ??= []).push(v);
  let css = header(title, `Figma collection: Primitives → ${prefixes.join(', ')}`);
  for (const [g, list] of Object.entries(groups)) {
    css += `\n  /* ---- ${g} ---- */\n`;
    list.sort((a, b) => (typeof a.value === 'number' && typeof b.value === 'number') ? a.value - b.value : a.name.localeCompare(b.name));
    for (const v of list) {
      const { out, note } = unitFn(v);
      css += `  ${cssName(v.name)}: ${out};${note ? `  /* ${note} */` : ''}\n`;
      addTok({ category: prefixes[0].split('-')[0] === 'font' || prefixes[0] === 'line-height' || prefixes[0] === 'letter-spacing' ? 'typography' : prefixes[0], file: title, group: g, figma: v.name, css: cssName(v.name), value: v.value, out, note: note || null });
    }
  }
  writeFileSync(OUT + `primitives-${title.toLowerCase().replace(/\s+/g, '-')}.css`, css + '}\n');
}
const px = (v) => {
  const r = round(v.value);
  const note = Number.isInteger(r) ? (v.value >= 200 ? 'very large — looks like a component dimension, review' : '') : 'non-integer px — review';
  return { out: `${r}px`, note };
};
numberFile(['spacing'], 'SPACING', px);
numberFile(['radius'], 'RADIUS', (v) => ({ out: `${round(v.value)}px`, note: v.value >= 100 ? 'pill/circle' : '' }), () => 'radius');
numberFile(['opacity'], 'OPACITY', (v) => v.name.includes('fraction')
  ? { out: `${round(v.value)}`, note: 'already 0–1 (rest of scale is 0–100) — inconsistent unit, review' }
  : { out: `${round(v.value / 100)}`, note: `${v.value}%` }, (n) => n.includes('fraction') ? 'opacity/fraction' : 'opacity');
numberFile(['font-family', 'font-size', 'font-weight', 'line-height', 'letter-spacing'], 'TYPOGRAPHY', (v) => {
  if (v.name.startsWith('font-family')) {
    const fallback = v.value.toLowerCase().includes('icon') ? '' : ', system-ui, sans-serif';
    return { out: `'${v.value}'${fallback}`, note: '' };
  }
  if (v.name.startsWith('font-weight')) return { out: `${v.value}`, note: '' };
  return { out: `${round(v.value)}px`, note: '' };
}, (n) => n.split('/')[0]);

// Effect styles → shadows
{
  let css = header('SHADOW', 'Figma effect styles (shadows cannot be variables)');
  for (const s of src.effectStyles) {
    const name = cssName('shadow/' + s.name);
    if (!s.effects.length) { css += `  /* "${s.name}" — EMPTY effect style in Figma (no effects), skipped — review */\n`; addTok({ category: 'shadow', group: 'shadow', figma: s.name, css: null, value: null, note: 'empty effect style' }); continue; }
    const val = s.effects.map(e => `${e.type === 'INNER_SHADOW' ? 'inset ' : ''}${e.x}px ${e.y}px ${e.blur}px ${e.spread || 0}px ${e.color}`).join(', ');
    css += `  ${name}: ${val};\n`;
    addTok({ category: 'shadow', group: 'shadow', figma: s.name, css: name, value: val });
  }
  writeFileSync(OUT + 'primitives-shadow.css', css + '}\n');
}

// Text styles → composite classes (reference primitives where an exact match exists)
{
  const sizeVar = Object.fromEntries(prims.filter(v => v.name.startsWith('font-size/')).map(v => [v.value, cssName(v.name)]));
  const weightVar = Object.fromEntries(prims.filter(v => v.name.startsWith('font-weight/')).map(v => [v.name.split('/').pop().toLowerCase(), cssName(v.name)]));
  const famVar = Object.fromEntries(prims.filter(v => v.name.startsWith('font-family/')).map(v => [v.value, cssName(v.name)]));
  const styleWeight = { light: 300, regular: 400, medium: 500 };
  let css = `/* ============================================================================
   TRINITY DESIGN SYSTEM — TEXT STYLES (composites of typography primitives)
   Source: Figma local text styles · GENERATED by scripts/build-primitives.mjs
   Uses primitive vars where an exact primitive exists; raw values otherwise (flagged).
   ============================================================================ */\n\n`;
  for (const t of src.textStyles) {
    const cls = '.text-' + t.name.toLowerCase().replace(/[\/\s]+/g, '-');
    const notes = [];
    const fam = famVar[t.family] ? `var(${famVar[t.family]})` : (notes.push(`family "${t.family}" has no primitive`), `'${t.family}'`);
    const size = sizeVar[t.size] ? `var(${sizeVar[t.size]})` : (notes.push(`${t.size}px has no font-size primitive`), `${t.size}px`);
    const w = t.style.toLowerCase();
    const weight = weightVar[w] ? `var(${weightVar[w]})` : `${styleWeight[w] ?? 400}`;
    const lh = t.lh.unit === 'PERCENT' ? `${round(t.lh.value / 100)}` : t.lh.unit === 'PIXELS' ? `${t.lh.value}px` : 'normal';
    if (t.lh.unit === 'PERCENT') notes.push('line-height is % (not bound to line-height primitives)');
    const ls = t.ls.unit === 'PERCENT' ? `${round(t.ls.value / 100)}em` : `${t.ls.value}px`;
    css += `${cls} {\n  font-family: ${fam};\n  font-size: ${size};\n  font-weight: ${weight};\n  line-height: ${lh};\n  letter-spacing: ${ls};\n}${notes.length ? `  /* ${notes.join('; ')} */` : ''}\n`;
    addTok({ category: 'textStyle', group: t.name.split('/')[0], figma: t.name, css: cls, value: { family: t.family, style: t.style, size: t.size, lh, ls }, note: notes.join('; ') || null });
  }
  writeFileSync(OUT + 'text-styles.css', css);
}

// Index
writeFileSync(OUT + 'index.css', `/* Trinity primitives — import order: raw values first, composites last. GENERATED. */
@import './primitives-color.css';
@import './primitives-data-color.css';
@import './primitives-spacing.css';
@import './primitives-radius.css';
@import './primitives-opacity.css';
@import './primitives-typography.css';
@import './primitives-shadow.css';
@import './text-styles.css';
`);
for (const t of tokens) t.usedBy = usage[t.figma] ?? [];
writeFileSync(OUT + 'primitives.json', JSON.stringify({ meta: src._meta, tokens }, null, 1));
const count = tokens.reduce((a, t) => ((a[t.category] = (a[t.category] || 0) + 1), a), {});
console.log('built', tokens.length, 'tokens', count);
